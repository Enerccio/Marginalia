package com.github.enerccio.marginalia.extensions.stconverter.service;

/**
 * The default prompt of the wand in Korean; the JSON fields are the English ones.
 */
public class DefaultsKO extends Defaults {

    @Override
    public String prompt() {
        return """
[ 너는 경험 많은 이야기 편집자다. 작가는 롤플레이 채팅을 한 차례씩 소설로 다시 쓰고 있다. 차례마다 작가는 장면 설정, 시점 인물, 등장인물, 무슨 일이 일어나는지에 대한 지시를 받아 그 차례의 본문을 쓴다. 너의 과제는 아래 채팅을 읽고 그런 차례들로 나누는 것이다. ]

### 배경 설정
{{backgroundLore}}

### 채팅
아래 메시지들은 쓰인 순서대로의 채팅, 메시지 {{firstMessage}}부터 {{lastMessage}}까지다. 각 메시지는 번호와 쓴 사람의 이름 아래에 있다. 사용자의 메시지는 사용자의 캐릭터가 하거나 말하는 것이고, 캐릭터의 메시지는 그에 대한 이야기의 응답이다.

{{chat}}

{{#if previousTurn}}
### 이야기가 놓인 지점
메시지 {{firstMessage}} 이전의 차례들은 이미 끝났다. 그중 마지막 차례에는 다음 정보가 있으니, 거기서부터 이어 가라. 채팅이 바꿀 때까지 같은 시점 인물과 같은 장면(장소, 시간, 등장인물)을 유지하고, 그 정보가 이미 말하는 것은 다시 말하지 마라.

{{previousTurn}}

{{/if}}
### 지침
1. 채팅을 자연스러운 전환점(장소, 시간, 시점, 상황이 바뀔 때, 또는 행동의 한 부분이 끝날 때)에서 메시지가 쓰인 순서대로 차례로 나눠라. 한 차례는 이어지는 하나 이상의 메시지로 이루어진다. 모든 차례를 합치면 {{firstMessage}}부터 {{lastMessage}}까지의 메시지를 정확히 한 번씩 덮어야 하며, 빠진 메시지도 두 차례에 들어간 메시지도 없어야 한다. 대사 한 줄이 아니라 이야기의 한 장면이 될 만큼 긴 차례를 선호하라.
2. 한 차례가 어떤 메시지들로 이루어지는지는 "firstMessage"와 "lastMessage"(머리글의 번호)로 밝혀라.
3. "sceneSetting": 그 차례가 어디서 언제 일어나는지, 거기에 누가 그리고 무엇이 있는지, 장면에서 무엇이 중요한지. 채팅과 배경 설정에서 가져오고, 채팅이 뒷받침하지 않는 것은 지어내지 마라.
4. "povCharacter": 그 차례를 서술하는 단 한 명의 인물, 채팅에서 쓰는 이름으로. 이야기가 정말로 시점을 바꾸지 않는 한 차례마다 같은 인물을 유지하라.
5. "presentCharacters": 장면에 참여하거나 장면에 있는 인물들의 이름, 쉼표로 구분.
6. "instructions": 작가가 그 차례에 써야 할 것을 지시로: 일어나는 순서대로의 사건, 인물들이 하고 말하고 느끼는 것, 남겨야 할 채팅의 세부, 차례가 어떻게 끝나는지. 작가가 채팅을 보지 않고도 차례를 쓸 수 있도록 메시지가 말하는 모든 것이 들어 있어야 한다. 이야기를 이어 가지 말고, 일어난 일을 바꾸지 말고, 배경 설정을 존중하라.

### 출력
응답 형식이 요구하는 JSON 객체로만 답하라: 위 필드들로 된 "turns" 목록. 도입도 설명도 없이.
""";
    }
}
