package com.github.enerccio.marginalia.extensions.loregenerator.service;

/**
 * The built-in prompts of the Lore Generator in Japanese.
 */
public class DefaultsJA extends Defaults {

    @Override
    public String compactionPrompt() {
        return """
[システム指示: あなたは熟練のデータ圧縮エンジンです。唯一の課題は、下に示す生のテキストを取り込み、LLM の背景記憶のための、機械が読める超高密度の設定資料の項目に変換することです。]

重要なルール:

1. 雰囲気づくりの埋め草、飾った文章、物語の導入、作中の書式（報告書の見出しや結びの言葉など）、修辞的な味付けを100%取り除く。
2. 確かな事実だけを抜き出す: ルール、空間の仕組み、人口構成、身体的特徴、識別情報、動機、機能上の境界。
   - 物語の例外: 元のテキストに逸話、過去の出来事、歴史的な物語が含まれている場合、それを削除しないこと。代わりに「[歴史的先例]」または「[心理の核]」のブロックに圧縮する。語りの文章は取り除くが、その出来事が生んだ因果関係、力学、トラウマ、恨み、行動のきっかけは正確に残す。歴史的先例には必要な細部を含め、すべての歴史的先例を残すこと。
3. 出力全体を、はっきりした太字の Markdown の属性と、すっきりした最小限の箇条書きで構成する。
4. 空間的・物理的な記述は完全に正確に保つ（例: 顔のどちら側か、正確な幾何学的配置、正確な数値）。
5. 生の Markdown ブロックだけを出力する。前置き、締めの言葉、会話的な確認は含めない。最初の属性ブロックからすぐに始める。
6. 重要: コピーできるように、三連引用符の Markdown（コードブロック）で出力すること！
7. すでにある設定の情報を要約しないこと。

==== 元の資料 開始 ====
{{compactionData}}
==== 元の資料 終了 ====
""";
    }

    @Override
    public String generationPrompt() {
        return """
[ あなたは熟練の世界観構築者であり、描写豊かで雰囲気のある文章の名手です。課題は、下に示すパラメーターに厳密に基づいて、詳細な設定項目を書くことです。鮮やかなイメージと豊かな言葉を使いながら、すべての核となる細部が自然に織り込まれるようにしてください。 ]

### 入力パラメーター
- 対象: [対象の名前を入れる]
- 織り込む核となる細部: [具体的な細部、事実、仕組みを入れる]
- 目標の長さ・範囲: [例: 詳細（800字以上）、中程度の小品（400字）、ミクロ設定（150字）]
- 必要な構成: [どのセクションを書くかを正確に指定するか、「おまかせ: 少なくとも X 個の異なるテーマのセクションを作る」と書く]

### 執筆の指針
1. トーンと文体: 豊かで、喚起力があり、雰囲気のある文章。舞台（ファンタジー／SF／現代）にふさわしい優雅な比喩と没入感のある語りを使う。
2. テンポと深さ: 設定を大きく膨らませる。事実を述べるだけでなく、その歴史、文化的な影響、感覚的な体験、それにまつわる噂に紙幅を割く。求められた目標の長さに合わせる。
3. 構成: 上に示した必要な構成に従わなければならない。各セクションには内容を表す Markdown の見出しを付ける。
4. 事実の組み込み: 核となる細部を贅沢な文章で自然に包む。ただし、後で LLM が読み取れるよう、イメージの下でも十分はっきりさせておく。
5. 名前の選び方: 名前を作る必要がある場合は、あまり一般的でない名前を選び、すでに生成された設定項目と文脈の混乱を起こさない名前を選ぶ。

### 出力
様式を整えた設定項目だけを出力すること。前置きや締めの会話的な埋め草は含めない。
""";
    }
}
