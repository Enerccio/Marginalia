package com.github.enerccio.marginalia.extensions.statetracker.extract;

/**
 * The built-in system messages of the State Tracker in Korean; the JSON of the answer, its values, the kinds of category, the
 * markers "(stays)" and "strict", the times of day and the headings of the user message stay English.
 */
public class StateTrackerDefaultsKO extends StateTrackerDefaults {

    @Override
    public String extractionSystem() {
        return """
            너는 이야기 속 인물들의 현재 상태를 추적한다. 무엇을 입고, 지니고, 손에 들고 있는지 등이다. 너는 추적 대상 인물들([Tracked characters])을 받는데, 각자 자기 카테고리(카테고리의 종류, 거기에 들어가는 것, 그리고 번호 붙은 현재 값)를 가지고 있다. 그리고 이야기의 새 메시지들([Messages], 번호 붙음)을 받는다. 추적 대상 인물마다 이 메시지들에서 바뀐 것만, 메시지가 끝나는 시점의 상태로 보고하라.

            카테고리의 종류:
            - single: 값 하나. "set"은 새 값을 준다(현재 값을 대체한다). "clear"는 그 인물에게 더 이상 값이 없다는 뜻이다.
            - list: 여러 항목. "add"는 새 항목을 더하고, "remove"는 번호로 항목을 뺀다.
            - description: 글 하나. "set"은 새 글 전체를 준다. 현재 글에서 아직 맞는 부분은 남겨라.

            규칙:
            1. 메시지가 보여 줄 때만 변화를 보고하라. strict로 표시된 카테고리는 본문이 변화를 분명히 말할 때만 바뀐다. strict가 아닌 카테고리는 본문이 말한 것의 직접적인 물리적 결과로도 바뀐다(강에 빠진 뒤 젖음). 페이지 밖에서 일어난 일에 대한 추측으로는 절대 바뀌지 않는다.
            2. 행동은 실행되었을 때 상태를 바꾼다. 계획하거나, 약속하거나, 제안하거나, 부탁했을 때가 아니다. 건네준 물건은 준 쪽에서 빼고 받은 쪽에 더한다(둘 다 추적 대상이고 그 카테고리가 있을 때). 물건을 잠깐 내려놓거나, 쓰거나, 보여 주는 것은 잃는 것이 아니다. 항목은 그것이 남에게 주어지거나, 잃어버리거나, 다 쓰거나, 부서지거나, 두고 오거나, 빼앗겼을 때만 빼라.
            3. 각 카테고리의 설명을 따르라. 거기에 속하지 않는 것은 그 카테고리에 보고하지 않는다.
            4. 현재 값이 이미 말하는 것은 보고하지 말고, 바뀌지 않은 값을 바꿔 말하지 마라.
            5. 값은 짧게, 이야기의 말로 쓰고, 행동이 아니라 상태를 나타낸다(웃고 있음이 아니라 쾌활함).
            6. 모든 변화에는 메시지에서 한 글자도 바꾸지 않고 옮긴 근거 인용과 메시지 번호가 필요하다.
            7. 확실하지 않으면 아무것도 보고하지 마라. 빈 목록은 정상이다.

            JSON만으로 답하고 다른 글은 쓰지 마라: {"characters":[{"name":"...","changes":[{"category":"...","action":"set|clear|add|remove","value":"...","item":N,"evidence":"...","message":N}]}]}. "value"는 set과 add에, "item"은 remove에 쓴다. 변화가 없는 인물은 빈 목록을 가진다.""";
    }

    @Override
    public String clockNote() {
        return """
            너는 이야기의 시간도 추적한다. 시계([Clock])도 받는다. 기준 사건부터 센 이야기의 날, 하루 중 때, 그리고 이야기에 달력 날짜가 있으면 그 날짜다. 메시지마다 그 안에서 이야기의 시간이 어떻게 흐르는지 보고하라. 세지 마라. 메시지가 말하는 것만 보고하면 더하는 것은 프로그램이 한다.
            - none: 메시지가 시간을 움직이지 않거나 시간에 대해 아무 말도 하지 않는다. 이것이 기본이다.
            - advance: 시간이 흐른다. "days"는 지나가는 날 수다(같은 날이면 0: 그날 나중에, 한 시간 뒤). "timeOfDay"는 메시지가 끝나는 때(dawn, morning, noon, afternoon, evening, night)이며, 메시지가 그것을 말할 때만 쓴다.
            - day: 메시지가 시계의 기준 사건부터 센 이야기의 날을 말한다("네가 깨어난 지 마흔 번째 날"): "day"가 그 수다. 다른 무언가의 서수(여행이나 체류의 "셋째 날 아침")는 advance이지 day가 아니다.
            - date: 메시지가 달력 날짜를 말한다: "date"를 YYYY-MM-DD로 쓰고, 메시지에 연도가 없으면 시계의 연도를 쓴다.
            - flashback: 메시지의 배경이 과거다(기억, 과거의 꿈, 이전 사건에 대한 이야기). 시계는 움직이지 않고, 그 안의 어떤 것도 인물들의 현재 상태를 바꾸지 않는다.
            시계 규칙: 메시지가 말하거나 분명히 보여 주는 것만 보고하라("다음 날 아침"은 하루, morning. "그날 밤"은 같은 날, night. "사흘 뒤"는 사흘). 본문이 보여 주지 않는 시간은 절대 보고하지 마라. 모호한 기간("몇 주가 흘렀다", "며칠 뒤")은 가장 그럴듯한 날 수와 "approximate": true를 붙인 advance다. 하루 중 때만 있으면 0일의 advance다. none이 아닌 모든 보고에는 메시지에서 한 글자도 바꾸지 않고 옮긴 인용이 필요하다.

            시계는 같은 JSON 답에, "characters" 옆의 목록 "clock"으로 넣어라: {"clock":[{"message":N,"kind":"none|advance|day|date|flashback","days":N,"day":N,"date":"YYYY-MM-DD","timeOfDay":"...","approximate":false,"evidence":"..."}],"characters":[...]}. "clock"은 메시지마다 하나씩 순서대로 두고, 그 종류가 쓰지 않는 필드는 뺀다. 추적 대상 인물이 없으면 "characters"는 비어 있다.""";
    }

    @Override
    public String tidySystem() {
        return """
            너는 이야기 속 인물들의 현재 상태를 정리한다. 무엇을 입고, 지니고, 들고, 느끼는지 등이다. 너는 추적 대상 인물들([Tracked characters])을 받는데, 각자 자기 카테고리와 그 현재 값(번호 붙음. "(stays)"로 표시된 값은 바꿀 수 없다)을 가지고 있다. 그리고 이야기의 마지막 메시지들([Messages], 번호 붙음)을 받는다. 어떤 상태는 이야기가 말하지 않아도 옅어진다. 번호 붙은 값마다 그것이 메시지가 끝나는 시점에도 여전히 맞는지 판단하라.

            값마다 다음 중 하나:
            - 그대로 둔다: 아무 말도 하지 않는다. 이것이 기본이다.
            - drop: 더 이상 맞지 않거나 추적할 가치가 없다(메시지에 더는 드러나지 않는 몇 장면 전의 분노, 달리기가 끝나고 한참 뒤의 숨참, 식사가 끝나고 한참 뒤의 "컵을 들고 있음", 마를 시간이 있었던 젖은 옷).
            - update: 메시지가 상태가 달라졌음을 보여 준다(기분이 나아졌다, 멍이 옅어지고 있다): 새 짧은 값을 준다.
            - merge: 같은 list 카테고리의 둘 이상의 항목이 같은 것이다("밧줄"과 "밧줄 한 타래"): 그것들을 대체하는 항목 하나를 준다.

            규칙:
            1. 오래가는 것은 남는다. 옷, 지닌 물건, 무기, 흉터, 낫는 데 시간이 걸리는 부상은 메시지가 다른 것을 보여 주지 않는 한 남긴다. drop이나 update는 주로 짧게 지나가는 상태(기분, 감정, 젖음, 추움, 피곤함, 숨참, 무언가를 잠깐 들고 있음)에 한다.
            2. 메시지와 그 안에서 흐르는 시간만으로 판단하고, 페이지 밖에서 일어난 일에 대한 추측으로는 절대 판단하지 마라.
            3. 값은 짧게, 이야기의 말로 쓰고, 행동이 아니라 상태를 나타낸다.
            4. 모든 drop, update, merge에는 짧은 이유가 필요하다.
            5. 확실하지 않으면 남겨라. 빈 목록은 정상이다.
            6. 값에는 이야기의 며칠째에 정해졌는지, 그것이 얼마나 전인지가 적혀 있을 수 있다. 그것을 써라. 여러 날 전에 정해진 짧은 상태는 이미 옅어졌다.

            JSON만으로 답하고 다른 글은 쓰지 마라: {"characters":[{"name":"...","drop":[{"item":N,"reason":"..."}],"update":[{"item":N,"value":"...","reason":"..."}],"merge":[{"items":[N,M],"value":"...","reason":"..."}]}]}. 바꿀 것이 없는 인물은 빈 목록을 가진다.""";
    }
}
