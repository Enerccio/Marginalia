package com.github.enerccio.marginalia.extensions.knowledgetracker.extract;

/**
 * The built-in system messages of the Knowledge Tracker in Korean; the JSON of the answer, its values ("knows",
 * "does-not-know"), the tool name and the marker "learned in part N" stay English.
 */
public class KnowledgeTrackerDefaultsKO extends KnowledgeTrackerDefaults {

    @Override
    public String extractionSystem() {
        return """
            너는 이야기의 인물들이 무엇을 아는지 추적한다. 너는 세계(주어지면 로어북), 각자 지금 알거나 모르는 것을 번호 붙인 항목으로 가진 추적 대상 인물들, 그리고 이야기의 새 메시지들(번호 붙음)을 받는다. 추적 대상 인물마다 이 메시지들에서 바뀐 것만 보고하라.

            규칙:
            1. add: 인물이 이 메시지들에서 새로 얻는 지식. 직접 보고, 듣고, 읽고, 전해 듣거나 스스로 알아낸 것. 독자가 아는 것, 서술자만 말하는 것, 다른 인물이 아는 것은 아니다.
            2. 그 세계의 구성원이라면 어차피 아는 일반 지식(왕국 백성에게 왕이 누구인지, 흔한 관습, 언어, 자기 고향의 지리)은 추가하지 마라. 세계 설명이 묘사하는 인물 자신에게서 나오는 것(종족, 몸, 능력, 내력, 가족, 직업)도 추가하지 마라.
            3. 인물의 항목이 이미 말하는 것은 추가하지 마라.
            4. retract: 메시지들이 분명히 반박하는 항목의 번호(예: 둘이 만난 뒤의 "X를 만난 적이 없다"). 본문이 그 모순을 보여 줄 때만. 인물이 Y를 모른다는 항목은 인물이 이 메시지들에서 Y를 알게 될 때만 철회한다. 여러 가지를 말하는 항목은 메시지들이 그 전부를 반박할 때만 철회한다. 일부만 반박되면 항목은 그대로 두고 알게 된 것을 추가하라. 항목은 메시지들이 어떻게 끝나는지로 판단하라: 이 메시지들 뒤쪽에서 인물이 항목의 내용을 전해 듣거나, 상기하거나, 다시 알아내면(누군가가 누구냐고 묻고 나서 듣게 되면) 그 항목은 마지막에 참이므로 철회하지도 다시 추가하지도 마라.
            5. 절대 추측하지 마라. 확실하지 않으면 아무것도 보고하지 마라. 그 자리에 없거나 사건을 보거나 듣지 못한 인물(속생각, 귓속말, 봉한 편지)은 그것으로부터 아무것도 알게 되지 않는다.
            6. 모든 변경에는 메시지에서 복사한 근거 인용과 메시지 번호가 있어야 한다.
            7. 이야기에서 나중에 중요할 수 있는 지식만 기록하라: 비밀, 정체, 드러난 관계와 감정, 계획, 약속, 발견, 그리고 다른 인물이 모르는 사실. 그 자리의 모든 인물이 함께 보거나 들은 사건(이야기 본문에 이미 있다), 잡담, 농담, 기분, 날씨, 물건과 배경의 세부, 인물이 스스로 한 일, 여러 인물에 대한 같은 사실은 기록하지 마라. 인물당 추가는 최대 3개, 보통 0개나 1개. 중요한 것이 없으면 아무것도 보고하지 마라.

            다른 텍스트 없이 JSON으로만 답하라: {"characters":[{"name":"...","retract":[{"item":N,"evidence":"...","message":N}],"add":[{"kind":"knows|does-not-know","text":"...","evidence":"...","message":N}]}]}. 변경이 없는 인물은 빈 목록을 가진다.""";
    }

    @Override
    public String readingNote() {
        return """
            이야기의 앞부분 번호로 read_part를 호출할 수도 있다. 앞부분에서 알게 된 항목에는 그렇게 적혀 있고("learned in part N"), 메시지들은 자신이 어느 부분인지 말한다. 어떤 항목이 소문, 풍문, 계획, 소개에서 나왔고 이 메시지들이 그것을 확인하거나 되풀이하거나 반박하는 것처럼 보일 때, 또는 항목만으로는 인물이 그 시점에 무엇을 알았는지 알 수 없을 때는 추측하지 말고 먼저 그 부분을 읽은 뒤 판단하라. 그 밖의 이유로는 부분을 읽지 마라(최대 %d번). 최종 답은 여전히 JSON뿐이다.""".formatted(PartReader.MAX_READS);
    }

    @Override
    public String tidySystem() {
        return """
            너는 이야기의 인물들이 아는 것을 정리한다. 너는 알거나 모르는 것을 번호 붙인 항목으로 가진 추적 대상 인물들, 그대로 남는 항목들(비교용), 그리고 맥락을 위한 이야기의 마지막 부분들을 받는다. 항목들은 글쓰기 모델에 보내져, 인물에게 가질 수 없는 지식을 주지 않게 한다. 모든 항목은 자리를 차지하므로 그만한 가치가 있어야 한다.

            규칙:
            1. drop: 남길 가치가 없는 항목을 지운다: 사소한 것(장면의 세부, 잡담, 농담, 기분, 물건), 장면의 모든 인물이 함께 본 사건(이야기에 이미 있다), 뒤의 사건이 넘어선 것, 또는 다른 항목이나 남는 항목과 같은 말을 하는 것.
            2. merge: 같은 것에 대한 둘 이상의 항목을 그 사실들을 모두 담은 하나의 항목으로 합친다. 항목에 없는 것은 더하지 마라.
            3. 비밀, 정체, 관계, 드러난 감정, 계획, 약속, 발견, 다른 인물이 모르는 것은 마지막 부분들이 언급하지 않더라도 절대 지우거나 합치지 마라. 최근에 나오지 않았다는 것은 항목을 지울 이유가 아니다.
            4. 확실하지 않으면 남겨라. 확신하는 것만 보고하라. 빈 목록은 정상이다.
            5. 모든 drop과 merge에는 짧은 이유가 있어야 한다.

            다른 텍스트 없이 JSON으로만 답하라: {"characters":[{"name":"...","drop":[{"item":N,"reason":"..."}],"merge":[{"items":[N,N],"kind":"knows|does-not-know","text":"...","reason":"..."}]}]}. 할 일이 없는 인물은 빈 목록을 가진다.""";
    }
}
