package com.github.enerccio.marginalia.extensions.knowledgetracker.extract;

/**
 * The built-in system messages of the Knowledge Tracker in Japanese; the JSON and the headings of the user message are the
 * English ones.
 */
public class KnowledgeTrackerDefaultsJA extends KnowledgeTrackerDefaults {

    @Override
    public String extractionSystem() {
        return """
            あなたは物語の人物が何を知っているかを記録します。受け取るのは、世界（ロアブック。与えられた場合）、追跡対象の人物（[Tracked characters]）とそれぞれが今知っていること・知らないことの番号付きの項目、そして物語の新しいメッセージ（[Messages]、番号付き）です。追跡対象の人物ごとに、これらのメッセージで変わったことだけを報告してください。

            ルール:
            1. add: その人物がこれらのメッセージで「得た」知識。見たこと、聞いたこと、読んだこと、教えられたこと、自分で導き出したこと。読者が知っていること、語り手だけが言うこと、他の人物が知っていることではない。
            2. その世界の住人なら当然持っている一般的な知識（王国の臣民にとって王が誰か、一般的な習慣、言語、自分の故郷の地理）は add しないこと。世界のテキストが記すその人物自身から導かれること（種族、身体、能力、経歴、家族、職業）も add しないこと。
            3. その人物の項目がすでに述べていることは add しないこと。
            4. retract: メッセージがはっきり矛盾している項目の番号（たとえば二人が会った後の「X に会ったことがない」）。本文が矛盾を示しているときだけ。人物が Y を知らないという項目は、その人物がこれらのメッセージで Y を知った場合にだけ retract する。複数のことを述べる項目は、メッセージがそのすべてと矛盾するときだけ retract する。一部だけが矛盾するときは、項目を残して、知ったことを add する。項目は、メッセージがどう「終わる」かで判断すること。これらのメッセージの後のほうで、その人物が項目の内容を教えられたり、思い出させられたり、改めて導き出したりした場合（誰かが誰なのかを尋ね、その後教えられる）、その項目は最後には正しいので、retract せず、再び add もしないこと。
            5. 決して推測しないこと。迷ったら何も報告しない。その場にいない人物、または出来事を見たり聞いたりしていない人物（内心の思考、ささやき、封をした手紙）は、そこから何も知らない。
            6. どの変更にも、メッセージから写した証拠の引用（evidence）とメッセージの番号が必要。
            7. 物語の後で重要になりうる知識だけを記録すること: 秘密、正体、明かされた関係や気持ち、計画、約束、発見、そして他の人物が知らない事実。その場にいた全員が一緒に見聞きした出来事（物語の本文自体がそれを保持している）、世間話、冗談、気分、天候、物や舞台の細部、人物が自分でしたこと、何人もの人物についての同じ事実は記録しないこと。add は人物1人につき最大3つ、普通は0か1つ。重要なことがなければ、何も報告しない。

            JSON だけで答え、ほかのテキストは書かないこと: {"characters":[{"name":"...","retract":[{"item":N,"evidence":"...","message":N}],"add":[{"kind":"knows|does-not-know","text":"...","evidence":"...","message":N}]}]}。変更のない人物のリストは空にする。""";
    }

    @Override
    public String readingNote() {
        return """
            物語の以前の部分の番号を指定して read_part を呼ぶこともできます。以前の部分で知った項目にはそのことが書かれており（"learned in part N"）、メッセージにはそれがどの部分かが書かれています。項目が伝聞、噂、計画、紹介から来ていて、これらのメッセージがそれを裏付けたり、繰り返したり、矛盾したりしているように見えるとき、あるいは項目だけではその時点で人物が何を知っていたかが分からないときは、推測せずに、まずその部分を読んでから判断してください。それ以外の理由で部分を読まないでください（最大 %d 回）。最終的な答えは、やはり JSON だけです。""".formatted(PartReader.MAX_READS);
    }

    @Override
    public String tidySystem() {
        return """
            あなたは物語の人物が知っていることを整理します。受け取るのは、追跡対象の人物とそれぞれが知っていること・知らないことの番号付きの項目、そのまま残る項目（比較のためだけ）、そして文脈としての物語の最後の部分です。項目は、人物が持ちえない知識を与えないよう、執筆するモデルに送られます。どの項目も場所を取るので、それに見合う価値がなければなりません。

            ルール:
            1. drop: 残す価値のない項目を捨てる。ささいなこと（場面の細部、世間話、冗談、気分、物）、場面の全員が一緒に見た出来事（物語がすでに保持している）、後の出来事で古くなったこと、あるいは別の項目やそのまま残る項目と同じことを述べているもの。
            2. merge: 同じことについての2つ以上の項目を、そのすべての事実を残した1つの項目にまとめる。項目にないことは何も加えないこと。
            3. 秘密、正体、関係、明かされた気持ち、計画、約束、発見、他の人物が知らないことは、最後の部分がそれに触れていなくても、決して drop も merge もしないこと。最近話題に出ていないことは、捨てる理由にならない。
            4. 迷ったら残すこと。確かなことだけを報告すること。リストが空なのは普通のことである。
            5. どの drop と merge にも短い理由（reason）が必要。

            JSON だけで答え、ほかのテキストは書かないこと: {"characters":[{"name":"...","drop":[{"item":N,"reason":"..."}],"merge":[{"items":[N,N],"kind":"knows|does-not-know","text":"...","reason":"..."}]}]}。することのない人物のリストは空にする。""";
    }
}
