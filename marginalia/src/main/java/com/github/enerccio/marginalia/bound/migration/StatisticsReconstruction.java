package com.github.enerccio.marginalia.bound.migration;

import com.github.enerccio.marginalia.domain.collections.RevisionDetail;
import com.github.enerccio.marginalia.domain.collections.RevisionSource;
import com.github.enerccio.marginalia.domain.components.StatisticCounts;

import java.time.LocalDate;
import java.time.ZoneId;
import java.util.*;

/**
 * Works out what the statistics of a book would have been, from what the application kept of it: the parts, with the day they were
 * made and deleted, and the versions of their text ({@code MessageRevision}) with their source, word and token counts. No database,
 * so the rules can be tested alone; {@link StatisticsBackfillMigration} reads the rows and writes the result.
 * <p>
 * The rules are those of the live counting ({@link StatisticCounts#ofVersion}): the first version of a part is a part created and its
 * words written or generated by who wrote it, a later one is an edit whose change of the word count is written / generated when
 * positive and removed when negative; a copy, a saved version, an import and a repair count nothing; a version of an agent (and its
 * merge into the book, the only trace of the work) goes to the agents' side. A deleted part is a part deleted with its words removed,
 * on the day of its last change. The tokens are an estimate (the real counts of the calls were not kept): the tokens of the generated
 * versions, and the prompt tokens the part saved. Nothing is rebuilt for the day of the migration or after it, those days are counted live.
 */
public final class StatisticsReconstruction {

    private StatisticsReconstruction() {
    }

    /**
     * @param promptTokens the prompt tokens of the last generation of the part, null if not saved
     * @param modelUsed    the model that wrote the part, blank for a part that was typed
     */
    public record PartRow(long id, String uuid, Long parentId, Date creation, Date modification, boolean deleted, int words,
                          long tokens, Long promptTokens, String modelUsed) {
    }

    /**
     * A version of a part, in the order it was made.
     */
    public record VersionRow(long partId, Date creation, RevisionSource source, String detail, boolean agent, int words, long tokens) {
    }

    /**
     * @param deleted     the book is in the trash: its parts are deleted with it, not one by one
     * @param activeLeaf  the id of the part the book is at now, the branch of the size rows ends there
     */
    public record BookRow(String uuid, boolean deleted, Long activeLeaf) {
    }

    public record CountRow(LocalDate day, boolean agent, StatisticCounts counts, Date lastChange) {
    }

    public record SizeRow(LocalDate day, long bookWords, long bookTokens, long branchWords, long branchTokens, String leafUuid) {
    }

    public record Result(List<CountRow> counts, List<SizeRow> sizes) {

        public boolean isEmpty() {
            return counts.isEmpty() && sizes.isEmpty();
        }
    }

    private static final class Accumulated {
        StatisticCounts counts = StatisticCounts.ZERO;
        Date lastChange;

        void add(StatisticCounts delta, Date when) {
            counts = counts.plus(delta);
            if (lastChange == null || when.after(lastChange)) {
                lastChange = when;
            }
        }
    }

    private record Key(LocalDate day, boolean agent) {
    }

    /**
     * One change of the size of a part, on a day.
     */
    private record Change(LocalDate day, long partId, long words, long tokens) {
    }

    /**
     * @param versions the versions of all the parts, each part's in the order they were made
     * @param today    the first day that is not rebuilt
     */
    public static Result rebuild(BookRow book, List<PartRow> parts, List<VersionRow> versions, LocalDate today, ZoneId zone) {
        Map<Long, List<VersionRow>> byPart = new HashMap<>();
        for (VersionRow version : versions) {
            byPart.computeIfAbsent(version.partId(), _ -> new ArrayList<>()).add(version);
        }
        Map<Key, Accumulated> counted = new TreeMap<>(Comparator.comparing(Key::day).thenComparing(Key::agent));
        List<Change> changes = new ArrayList<>();

        for (PartRow part : parts) {
            List<VersionRow> history = byPart.getOrDefault(part.id(), List.of());
            if (history.isEmpty()) {
                // the history was off, or the part is older than it: the part itself is the one version
                if (part.words() <= 0) {
                    continue;
                }
                boolean model = part.modelUsed() != null && !part.modelUsed().isBlank();
                history = List.of(new VersionRow(part.id(), part.creation(), model ? RevisionSource.GENERATE : RevisionSource.HUMAN,
                        null, false, part.words(), part.tokens()));
            }
            Integer previous = null;
            VersionRow lastModel = null;
            LocalDate lastDay = null;
            for (VersionRow version : history) {
                LocalDate day = dayOf(version.creation(), zone);
                lastDay = lastDay == null || day.isAfter(lastDay) ? day : lastDay;
                changes.add(new Change(day, part.id(), version.words(), version.tokens()));
                if (counts(version) && day.isBefore(today)) {
                    boolean agent = agentSide(version);
                    StatisticCounts delta = StatisticCounts.ofVersion(version.source(), previous, version.words());
                    if (version.source().isModel()) {
                        delta = delta.plus(new StatisticCounts(0, Math.max(0, version.tokens()), 1, 0, 0, 0, 0, 0, 0));
                    }
                    if (!delta.isZero()) {
                        counted.computeIfAbsent(new Key(day, agent), _ -> new Accumulated()).add(delta, version.creation());
                    }
                }
                if (version.source().isModel()) {
                    lastModel = version;
                }
                previous = version.words();
            }
            // the prompt of the last generation belongs to the day and the side of that generation
            if (part.promptTokens() != null && part.promptTokens() > 0 && part.modelUsed() != null && !part.modelUsed().isBlank()) {
                VersionRow carrier = lastModel != null ? lastModel : history.getFirst();
                LocalDate day = dayOf(carrier.creation(), zone);
                if (counts(carrier) && day.isBefore(today)) {
                    counted.computeIfAbsent(new Key(day, agentSide(carrier)), _ -> new Accumulated())
                            .add(new StatisticCounts(part.promptTokens(), 0, 0, 0, 0, 0, 0, 0, 0), carrier.creation());
                }
            }
            if (part.deleted() && !book.deleted()) {
                LocalDate day = dayOf(part.modification(), zone);
                if (lastDay != null && day.isBefore(lastDay)) {
                    day = lastDay;
                }
                changes.add(new Change(day, part.id(), 0, 0));
                if (day.isBefore(today)) {
                    counted.computeIfAbsent(new Key(day, false), _ -> new Accumulated())
                            .add(StatisticCounts.partsDeleted(1).plus(StatisticCounts.wordsRemoved(part.words())), part.modification());
                }
            }
        }

        List<CountRow> counts = new ArrayList<>();
        counted.forEach((key, value) -> counts.add(new CountRow(key.day(), key.agent(), value.counts, value.lastChange)));
        return new Result(counts, sizes(book, parts, changes, today));
    }

    /**
     * Imports were written elsewhere, a repair or a copy is not writing: the live counting skips them, so does this.
     */
    private static boolean counts(VersionRow version) {
        RevisionDetail detail = RevisionDetail.parse(version.detail());
        if (detail == RevisionDetail.ARCHIVE_IMPORT || detail == RevisionDetail.SILLYTAVERN_IMPORT) {
            return false;
        }
        return !(version.source() == RevisionSource.PLUGIN && (version.detail() == null || version.detail().isBlank()));
    }

    private static boolean agentSide(VersionRow version) {
        return version.agent() || RevisionDetail.parse(version.detail()) == RevisionDetail.AGENT_MERGE;
    }

    private static LocalDate dayOf(Date when, ZoneId zone) {
        return when.toInstant().atZone(zone).toLocalDate();
    }

    /**
     * The size of the book at the end of each day on which a part changed, for the days before today and only when it differs from
     * the day before: the sum over the parts that existed and were not deleted of the words and tokens of their newest version,
     * and the same for the parts on the branch of the active leaf.
     */
    private static List<SizeRow> sizes(BookRow book, List<PartRow> parts, List<Change> changes, LocalDate today) {
        Map<Long, PartRow> byId = new HashMap<>();
        parts.forEach(part -> byId.put(part.id(), part));
        Set<Long> branch = new HashSet<>();
        String leafUuid = null;
        if (book.activeLeaf() != null && byId.containsKey(book.activeLeaf())) {
            leafUuid = byId.get(book.activeLeaf()).uuid();
            for (PartRow at = byId.get(book.activeLeaf()); at != null && branch.add(at.id());
                 at = at.parentId() == null ? null : byId.get(at.parentId())) {
                // up to the first part
            }
        }
        // a stable sort: the changes of a part stay in the order they were made
        List<Change> ordered = new ArrayList<>(changes);
        ordered.sort(Comparator.comparing(Change::day));
        Map<Long, long[]> current = new HashMap<>();
        long bookWords = 0, bookTokens = 0, branchWords = 0, branchTokens = 0;
        long[] last = {0, 0, 0, 0};
        List<SizeRow> rows = new ArrayList<>();
        int i = 0;
        while (i < ordered.size()) {
            LocalDate day = ordered.get(i).day();
            if (!day.isBefore(today)) {
                break;
            }
            for (; i < ordered.size() && ordered.get(i).day().equals(day); i++) {
                Change change = ordered.get(i);
                long[] before = current.getOrDefault(change.partId(), new long[]{0, 0});
                bookWords += change.words() - before[0];
                bookTokens += change.tokens() - before[1];
                if (branch.contains(change.partId())) {
                    branchWords += change.words() - before[0];
                    branchTokens += change.tokens() - before[1];
                }
                current.put(change.partId(), new long[]{change.words(), change.tokens()});
            }
            long[] now = {bookWords, bookTokens, branchWords, branchTokens};
            if (!Arrays.equals(now, last)) {
                rows.add(new SizeRow(day, bookWords, bookTokens, branchWords, branchTokens, leafUuid));
                last = now;
            }
        }
        return rows;
    }

}
