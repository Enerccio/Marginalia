package com.github.enerccio.marginalia.domain.model.impl;

import com.github.enerccio.marginalia.domain.collections.AgentRunStatus;
import com.github.enerccio.marginalia.domain.model.ExtendableEntity;
import com.github.enerccio.marginalia.domain.traits.CleanupReference;
import com.github.enerccio.marginalia.domain.traits.CleanupReference.Policy;
import com.github.enerccio.marginalia.domain.traits.ExtendedAttribute;
import jakarta.persistence.*;

import java.util.Date;

/**
 * One execution of an {@link Agent}: the whole job, whatever threads (sub-agents) it spawns. A run is a normal object
 * the user can list, trash and, when paused or stopped with the copy kept, resume.
 * <p>
 * The status and the counters are changed by SQL updates of the repository ({@code AgentRunService#transition},
 * {@code AgentRunService#addUsage}), so that a runner thread, the console and parallel threads of the run don't lose
 * each other's changes. Their columns are not {@code updatable}: saving a stale copy of the run (what every save of a
 * detached entity does) never writes them back, and their setters have an effect on a new run only.
 * <p>
 * The folder of the run on the disk is derived from the uuid ({@code <data>/agent-runs/<uuid>}), no path is stored.
 */
@Entity
@Table(name = "agent_runs")
public class AgentRun extends ExtendableEntity {

    // a soft deleted agent takes its runs with it
    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "agent_id")
    @CleanupReference(Policy.OWNED_BY)
    private Agent agent;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 32, updatable = false)
    private AgentRunStatus status = AgentRunStatus.RUNNING;

    /**
     * Why the run is in this status when it is not obvious (the error of a failed run, what a pause waits for), shown
     * to the user.
     */
    @Column(length = 2000, updatable = false)
    private String statusReason;

    /**
     * The user should look at the run (it waits for them, finished, failed...) and has not yet: set with every change
     * of the status ({@link AgentRunStatus#needsAttention}), cleared by {@code AgentRunService.acknowledge}. A column
     * because it is asked in SQL; the user may be away for days while the run works.
     */
    @Column(nullable = false, updatable = false)
    private boolean attention;

    // the hidden copy of the manuscript the agent works on (a new one for every run, deleted for good when the run
    // ends), nullable: null before the copy is made and after it is deleted. Eager, the runner takes the book from the
    // run and uses it on its own threads, a proxy would have no session there. The run owns it, the cleanup purges
    // the copy with the run
    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "workingCopy_id")
    @CleanupReference(Policy.OWNS)
    private Manuscript workingCopy;

    /**
     * Tokens sent to the models by the run, all its threads.
     */
    @Column(nullable = false, updatable = false)
    private long prefillTokens;

    /**
     * Tokens generated by the models for the run, reasoning included.
     */
    @Column(nullable = false, updatable = false)
    private long generatedTokens;

    /**
     * Number of the requests (rounds) of the run.
     */
    @Column(nullable = false, updatable = false)
    private long rounds;

    @Temporal(TemporalType.TIMESTAMP)
    private Date startedAt;

    /**
     * When the run stopped working (done, stopped, failed), empty while it works and again after it is resumed.
     */
    @Temporal(TemporalType.TIMESTAMP)
    @Column(updatable = false)
    private Date finishedAt;

    /**
     * Code of the language of the texts the agent sees (descriptions of commands, results and errors), the language of
     * the agent when the run was started. Neither the language of the user's interface nor the one of the book.
     */
    @Transient
    @ExtendedAttribute
    private String language;

    /**
     * Whether the run is a conversation with the user (started in the console): the agent's {@code finish} does not
     * end it, the report goes to the user and the run waits for their next message, until they press Finish or stop
     * it. An autonomous run (false) ends with {@code finish}. Set when the run starts, never changed.
     */
    @Transient
    @ExtendedAttribute
    private boolean interactive;

    public Agent getAgent() {
        return agent;
    }

    public void setAgent(Agent agent) {
        this.agent = agent;
    }

    public AgentRunStatus getStatus() {
        return status;
    }

    public void setStatus(AgentRunStatus status) {
        this.status = status;
    }

    public String getStatusReason() {
        return statusReason;
    }

    public void setStatusReason(String statusReason) {
        this.statusReason = statusReason;
    }

    public boolean isAttention() {
        return attention;
    }

    public void setAttention(boolean attention) {
        this.attention = attention;
    }

    public Manuscript getWorkingCopy() {
        return workingCopy;
    }

    public void setWorkingCopy(Manuscript workingCopy) {
        this.workingCopy = workingCopy;
    }

    public long getPrefillTokens() {
        return prefillTokens;
    }

    public void setPrefillTokens(long prefillTokens) {
        this.prefillTokens = prefillTokens;
    }

    public long getGeneratedTokens() {
        return generatedTokens;
    }

    public void setGeneratedTokens(long generatedTokens) {
        this.generatedTokens = generatedTokens;
    }

    /**
     * All the tokens the run spent, what the budget limits.
     */
    public long getTotalTokens() {
        return prefillTokens + generatedTokens;
    }

    public long getRounds() {
        return rounds;
    }

    public void setRounds(long rounds) {
        this.rounds = rounds;
    }

    public Date getStartedAt() {
        return startedAt;
    }

    public void setStartedAt(Date startedAt) {
        this.startedAt = startedAt;
    }

    public Date getFinishedAt() {
        return finishedAt;
    }

    public void setFinishedAt(Date finishedAt) {
        this.finishedAt = finishedAt;
    }

    public boolean isInteractive() {
        return interactive;
    }

    public void setInteractive(boolean interactive) {
        this.interactive = interactive;
    }

    public String getLanguage() {
        return language != null ? language : "en";
    }

    public void setLanguage(String language) {
        this.language = language;
    }
}
