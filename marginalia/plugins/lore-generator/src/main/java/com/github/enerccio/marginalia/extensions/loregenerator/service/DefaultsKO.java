package com.github.enerccio.marginalia.extensions.loregenerator.service;

/**
 * The built-in prompts of the Lore Generator in Korean.
 */
public class DefaultsKO extends Defaults {

    @Override
    public String compactionPrompt() {
        return """
[시스템 지시: 너는 숙련된 데이터 압축 엔진이다. 너의 유일한 과제는 아래에 주어진 원문을 받아들여, LLM의 배경 기억을 위한 기계가 읽을 수 있는 초고밀도 설정 자료 항목으로 바꾸는 것이다.]

핵심 규칙:

1. 분위기를 위한 군더더기, 화려한 미문, 서사적 도입, 작품 세계 안의 서식(보고서 머리글이나 맺음 인사 같은 것), 수사적 꾸밈을 100% 걷어 내라.
2. 확실한 사실만 뽑아내라: 규칙, 공간적 구조, 인구 구성, 신체적 특징, 식별 정보, 동기, 기능적 한계.
   - 서사 예외: 원문에 일화, 과거의 사건, 역사적 서술이 있으면 지우지 마라. 대신 "[역사적 선례]"나 "[심리적 핵심]" 블록으로 압축하라. 이야기식 산문은 걷어 내되, 그 사건이 만들어 낸 정확한 인과 관계의 역학, 트라우마, 원한, 행동의 계기는 보존하라. 역사적 선례에는 필요한 세부를 담고, 역사적 선례는 모두 남겨라.
3. 출력 전체를 굵은 글씨의 명확한 markdown 속성과 깔끔하고 간결한 글머리표로 구성하라.
4. 공간적, 신체적 묘사는 절대적으로 정확하게 유지하라(예: 얼굴의 어느 쪽인지, 정확한 기하학적 배치, 정확한 숫자).
5. 원본 markdown 블록만 출력하라. 도입, 마무리, 대화식 확인을 넣지 마라. 첫 속성 블록으로 바로 시작하라.
6. 중요: 복사할 수 있도록 백틱 세 개로 감싼 markdown(코드 블록)으로 출력하라!
7. 이미 있는 설정 자료의 정보는 요약하지 마라.

==== 원문 자료 시작 ====
{{compactionData}}
==== 원문 자료 끝 ====
""";
    }

    @Override
    public String generationPrompt() {
        return """
[ 너는 숙련된 세계관 설계자이자 묘사가 풍부하고 분위기 있는 산문의 대가다. 너의 과제는 아래에 주어진 매개변수에 엄격히 따라 상세한 설정 항목을 쓰는 것이다. 생생한 이미지와 풍부한 언어를 쓰되, 모든 핵심 세부가 자연스럽게 녹아들게 하라. ]

### 입력 매개변수
- 주제: [주제 이름을 넣는다]
- 엮어 넣을 핵심 세부: [구체적인 세부, 사실, 구조를 넣는다]
- 목표 분량 / 범위: [예: 심층 해설(800단어 이상), 중간 길이 소품(400단어), 짧은 설정(150단어)]
- 요구되는 구성: [어떤 섹션을 쓸지 정확히 적거나, "자유 선택: 서로 다른 주제의 섹션을 적어도 X개 만든다"라고 쓴다]

### 작성 지침
1. 어조와 문체: 풍부하고 환기적이며 분위기 있게. 배경(판타지 / SF / 현대)에 맞는 우아한 비유와 몰입감 있는 서술을 써라.
2. 호흡과 깊이: 설정을 넉넉히 확장하라. 사실만 말하지 말고, 그 역사, 문화적 영향, 감각적 경험, 둘러싼 소문에 지면을 할애하라. 요청된 목표 분량에 맞춰라.
3. 구성: 위에 주어진 요구 구성을 반드시 따라라. 섹션마다 설명적인 markdown 머리글을 써라.
4. 사실의 통합: 핵심 세부를 화려한 산문으로 자연스럽게 감싸라. 나중에 LLM이 읽어 낼 수 있도록 이미지 아래에서도 충분히 분명하게 남게 하라.
5. 이름 고르기: 이름을 지어야 하면 흔하지 않은 이름, 이미 만든 설정 항목과 문맥상 헷갈리지 않을 이름을 골라라.

### 출력
다듬어진 설정 항목만 내놓아라. 도입이나 마무리의 대화식 군말은 넣지 마라.
""";
    }
}
