package com.github.enerccio.marginalia.extensions.statetracker.extract;

/**
 * The built-in system messages of the State Tracker in Japanese; the JSON of the answer, its values, the kinds of category, the
 * markers "(stays)" and "strict", the times of day and the headings of the user message stay English.
 */
public class StateTrackerDefaultsJA extends StateTrackerDefaults {

    @Override
    public String extractionSystem() {
        return """
            あなたは物語の人物の現在の状態を記録します。身に着けているもの、持ち運んでいるもの、手に持っているものなどです。受け取るのは、追跡対象の人物（[Tracked characters]）とそれぞれのカテゴリー（カテゴリーの種類、そこに入るもの、現在の値。番号付き）、そして物語の新しいメッセージ（[Messages]、番号付き）です。追跡対象の人物ごとに、これらのメッセージで変わったことだけを、メッセージの最後の時点の状態で報告してください。

            カテゴリーの種類：
            - single：値は一つ。"set" は新しい値を与え（現在の値を置き換える）、"clear" はその人物がもう何も持っていないことを示す。
            - list：複数の項目。"add" は新しい項目を加え、"remove" は番号で項目を取り除く。
            - description：一つの文章。"set" は新しい文章全体を与える。現在の文章のうち、まだ当てはまる部分は残すこと。

            ルール：
            1. 変化は、メッセージがそれを示しているときだけ報告する。strict と記されたカテゴリーは、本文がその変化をはっきり述べたときだけ変わる。strict でないカテゴリーは、本文が述べたことの直接の物理的な結果でも変わる（川に落ちたあとで濡れている）。ページの外で起きたことの推測では決して変えない。
            2. 行動が状態を変えるのは、それが実行されたときであり、計画された、約束された、申し出られた、頼まれたときではない。手渡された物は渡した側から取り除き、受け取った側に加える（両方が追跡対象でそのカテゴリーを持つ場合）。物を少し置く、使う、見せるのは失うことではない。項目を取り除くのは、それが手放された、失われた、使い切られた、壊された、置いていかれた、奪われたときだけ。
            3. 各カテゴリーの説明に従う。そこに入らないものはそのカテゴリーに報告しない。
            4. 現在の値がすでに述べていることは報告せず、変わっていない値を言い換えない。
            5. 値は短く、物語の言葉で書き、行動ではなく状態を表す（「笑っている」ではなく「陽気」）。
            6. どの変化にも、メッセージから一字一句そのまま写した根拠の引用と、メッセージの番号が必要。
            7. 迷ったら何も報告しない。空のリストは普通のこと。

            JSON だけで答え、ほかの文章は書かないこと：{"characters":[{"name":"...","changes":[{"category":"...","action":"set|clear|add|remove","value":"...","item":N,"evidence":"...","message":N}]}]}。"value" は set と add に、"item" は remove に使う。変化のない人物は空のリストにする。""";
    }

    @Override
    public String clockNote() {
        return """
            あなたは物語の時間も記録します。時計（[Clock]）も受け取ります。基準となる出来事から数えた物語の日、時間帯、そして物語に暦の日付があればその日付です。メッセージごとに、その中で物語の時間がどう進むかを報告してください。数えないこと。メッセージが述べていることだけを報告すれば、足し算はプログラムが行います。
            - none：メッセージは時間を進めない、または時間について何も述べていない。これが既定。
            - advance：時間が経つ。"days" は経過する日数（同じ日のままなら 0：その日のうちに後で、一時間後）、"timeOfDay" はメッセージが終わる時間帯（dawn, morning, noon, afternoon, evening, night）。メッセージがそれを述べている場合のみ。
            - day：メッセージが時計の基準となる出来事から数えた物語の日を述べている（「目覚めてから四十日目」）："day" はその数。ほかの何かの序数（旅や滞在の「三日目の朝」）は advance であり、day ではない。
            - date：メッセージが暦の日付を述べている："date" を YYYY-MM-DD で。メッセージに年がなければ時計の年を使う。
            - flashback：メッセージが過去を舞台にしている（記憶、昔の夢、以前の出来事の語り）。時計は進まず、その中のことは人物の現在の状態を何も変えない。
            時計のルール：メッセージが述べていること、または明らかにしていることだけを報告する（「翌朝」は一日、morning。「その夜」は同じ日、night。「三日後」は三日）。本文が示さない時間は決して報告しない。あいまいな期間（「何週間かが過ぎた」「数日後」）は、いちばんもっともらしい日数と "approximate": true を付けた advance にする。時間帯だけなら 0 日の advance。none 以外の報告には、メッセージから一字一句そのまま写した引用が必要。

            時計は同じ JSON の答えに、"characters" と並ぶリスト "clock" として入れること：{"clock":[{"message":N,"kind":"none|advance|day|date|flashback","days":N,"day":N,"date":"YYYY-MM-DD","timeOfDay":"...","approximate":false,"evidence":"..."}],"characters":[...]}。"clock" はメッセージごとに一つずつ、順番に並べ、その種類が使わないフィールドは省く。追跡対象の人物がいなければ "characters" は空にする。""";
    }

    @Override
    public String tidySystem() {
        return """
            あなたは物語の人物の現在の状態を整理します。身に着けているもの、持ち運んでいるもの、持っているもの、感じていることなどです。受け取るのは、追跡対象の人物（[Tracked characters]）とそれぞれのカテゴリーと現在の値（番号付き。"(stays)" と記された値は変更できない）、そして物語の最後のメッセージ（[Messages]、番号付き）です。状態の中には、物語がそう言わなくても薄れていくものがあります。番号の付いた値ごとに、それがメッセージの最後の時点でまだ当てはまるかを判断してください。

            値ごとに、次のどれか一つ：
            - そのままにする：何も言わない。これが既定。
            - drop：もう当てはまらない、または追跡する価値がない（数場面前の怒りで、メッセージにもう表れていないもの、走ってからずっと後の息切れ、食事からずっと後の「カップを持っている」、乾く時間のあった濡れた服）。
            - update：メッセージが状態の移り変わりを示している（気分が良くなった、あざが薄れてきた）：新しい短い値を与える。
            - merge：同じ list カテゴリーの二つ以上の項目が同じものを指している（「ロープ」と「ロープの束」）：それらを置き換える一つの項目を与える。

            ルール：
            1. 長く続くものは残す。服、持ち物、武器、傷跡、治るのに時間がかかる怪我は、メッセージが別のことを示さない限り残す。drop や update の対象は主に一時的な状態（気分、感情、濡れている、寒い、疲れている、息が切れている、何かを少しの間持っている）。
            2. 判断はメッセージとその中で経つ時間だけから行い、ページの外で起きたことの推測では決して判断しない。
            3. 値は短く、物語の言葉で書き、行動ではなく状態を表す。
            4. drop、update、merge にはどれも短い理由が必要。
            5. 迷ったら残す。空のリストは普通のこと。
            6. 値には、物語の何日目に設定されたか、それがどれくらい前かが書かれていることがある。それを使うこと。何日も前に設定された一時的な状態はもう薄れている。

            JSON だけで答え、ほかの文章は書かないこと：{"characters":[{"name":"...","drop":[{"item":N,"reason":"..."}],"update":[{"item":N,"value":"...","reason":"..."}],"merge":[{"items":[N,M],"value":"...","reason":"..."}]}]}。変えることのない人物は空のリストにする。""";
    }
}
